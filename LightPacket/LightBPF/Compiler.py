# Size Modifiers for LD / LDX (code & 0x18)
BPF_W = 0x00  # 32 bits (4 bytes)
BPF_H = 0x08  # 16 bits (2 bytes)
BPF_B = 0x10  # 8 bits (1 byte)

# Addressing Modes for LD / LDX (code & 0xe0)
BPF_IMM = 0x00  # Immediate value
BPF_ABS = 0x20  # Absolute packet offset
BPF_IND = 0x40  # Packet offset indexed by Register X
BPF_MEM = 0x60  # Scratch memory M[k]
BPF_LEN = 0x80  # Packet length
BPF_MSH = 0xa0  # 4 * (packet[k] & 0x0f) -> loaded into X (IPv4 IHL)

# ALU Operations (code & 0xf0)
BPF_ADD = 0x00
BPF_SUB = 0x10
BPF_MUL = 0x20
BPF_DIV = 0x30
BPF_OR  = 0x40
BPF_AND = 0x50
BPF_LSH = 0x60
BPF_RSH = 0x70
BPF_NEG = 0x80
BPF_MOD = 0x90
BPF_XOR = 0xa0

# Jump Operations (code & 0xf0)
BPF_JA   = 0x00
BPF_JEQ  = 0x10
BPF_JGT  = 0x20
BPF_JGE  = 0x30
BPF_JSET = 0x40

# Source Operand (code & 0x08)
BPF_K = 0x00  # Constant / Immediate
BPF_X = 0x08  # Register X

# Misc Operations (code & 0xf8)
BPF_TAX = 0x00  # Register X = Register A
BPF_TXA = 0x80  # Register A = Register X

# Return operand mode
